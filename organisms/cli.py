#!/usr/bin/env python3
"""Server Organisms CLI — put the living colony in front of YOUR app.

Typical first run (from this repo, once)::

  python -m organisms init ../my-app --upstream http://host.docker.internal:8000
  python -m organisms up        # prints your private dashboard link
  python -m organisms status   # watch every API: traffic, attacks, immunity

Daily use: status, logs, kill, revive, down. doctor diagnoses problems.
"""
import argparse
import json
import os
import secrets
import subprocess
import sys
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GW = "http://127.0.0.1:18010"
SUP = "http://127.0.0.1:18012"

try:
    import requests as _rq

    HAVE_REQUESTS = True
except ImportError:
    HAVE_REQUESTS = False


def _env():
    vals = {}
    p = os.path.join(ROOT, ".env")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            if "=" in line and not line.startswith("#"):
                k, v = line.strip().split("=", 1)
                vals[k] = v
    return vals


def _write_env(updates):
    p = os.path.join(ROOT, ".env")
    lines = open(p, encoding="utf-8").read().splitlines() if os.path.exists(p) else []
    out, seen = [], set()
    for line in lines:
        if "=" in line and line.split("=", 1)[0] in updates:
            k = line.split("=", 1)[0]
            out.append(f"{k}={updates[k]}")
            seen.add(k)
        else:
            out.append(line)
    for k, v in updates.items():
        if k not in seen:
            out.append(f"{k}={v}")
    open(p, "w", encoding="utf-8").write("\n".join(out) + "\n")


def _get(url, token=None, timeout=10):
    if HAVE_REQUESTS:
        h = {"X-Broker-Token": token} if token else {}
        return _rq.get(url, headers=h, timeout=timeout)
    req = urllib.request.Request(url, headers={"X-Broker-Token": token} if token else {})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        class R:
            status_code = r.status
            text = r.read().decode()
            def json(self):
                return json.loads(self.text)
        return R()


def _post(url, token=None, payload=None, timeout=10):
    data = json.dumps(payload or {}).encode()
    if HAVE_REQUESTS:
        return _rq.post(url, headers={"X-Broker-Token": token or "", "Content-Type": "application/json"},
                        data=data, timeout=timeout)
    req = urllib.request.Request(url, data=data, method="POST",
                                 headers={"X-Broker-Token": token or "", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        class R:
            status_code = r.status
            text = r.read().decode()
            def json(self):
                return json.loads(self.text)
        try:
            return R()
        except Exception as e:
            class E:
                status_code = 0
                text = str(e)
                def json(self):
                    return {}
            return E()


def cmd_init(args):
    from organisms import scanner

    target = os.path.abspath(args.repo)
    if not os.path.isdir(target):
        print(f"error: not a directory: {target}", file=sys.stderr)
        return 2
    apis = scanner.scan(target)
    normals, excluded = scanner.safe_replay_normals(apis)
    app_name = os.path.basename(target.rstrip(os.sep)) or "my-app"
    outdir = os.path.join(ROOT, "adoption")
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "apis.json"), "w", encoding="utf-8") as f:
        json.dump({"source": target, "app": app_name, "apis": apis}, f, indent=1)
    env = _env()
    updates = {"UPSTREAM_URL": args.upstream, "REPLAY_NORMALS": ",".join(normals),
               "REPLAY_USER_ID": args.replay_user}
    for k in ("BROKER_TOKEN", "GATEWAY_TOKEN", "AUDIT_TOKEN", "IDENTITY_HMAC_KEY"):
        if not env.get(k):
            updates[k] = secrets.token_hex(32)
    _write_env(updates)
    if args.network:
        import re as _re

        if not _re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]*", args.network):
            print("error: --network must be a plain Docker network name", file=sys.stderr)
            return 2
        with open(os.path.join(ROOT, "docker-compose.override.yml"), "w", encoding="utf-8") as f:
            f.write(f"""# Generated by `organisms init --network`: join your app's Docker network
# so the gateway can reach your container by service name.
services:
  gateway:
    networks:
      - default
      - appnet
networks:
  appnet:
    external: true
    name: {args.network}
""")
    print(f"Discovered {len(apis)} API routes in {target} "
          f"({', '.join(sorted({a['framework'] for a in apis})) or 'unknown framework'}):")
    for a in apis[:25]:
        print(f"  {a['method']:6} {a['path']}")
    if len(apis) > 25:
        print(f"  ... and {len(apis) - 25} more")
    print(f"\n{app_name} is wired: UPSTREAM_URL={args.upstream}, {len(normals)} replay normals.")
    if excluded:
        print(f"Excluded from auto-replay (review before adding): {', '.join(excluded[:8])}")
    print("\nNext:  python -m organisms up")
    return 0


def cmd_up(args):
    r = subprocess.run(["docker", "compose", "up", "--build", "-d"], cwd=ROOT)
    if r.returncode != 0:
        return r.returncode
    env = _env()
    print("\nColony starting. Your private dashboard (do not share):")
    print(f"  http://127.0.0.1:18000/#token={env.get('BROKER_TOKEN', '')}&gwtoken={env.get('GATEWAY_TOKEN', '')}")
    print("Your APIs now flow:  internet -> gateway :18010 -> your app")
    return 0


def render_status(state):
    routes = state.get("routes", {})
    inv = {f"{a['method']} {a['path']}".replace("<uid>", "{id}").replace("<user_id>", "{id}")
           for a in state.get("inventory", [])}
    lines = [f"phase: {'KILLED (lease withdrawn)' if not state.get('lease_active') else ('immune' if state.get('active_rules') else 'healthy')}"
             f"   passed={state.get('allowed', 0)} blocked={state.get('blocked', 0)}"
             f"   immunities={len(state.get('active_rules', []))} pending={len(state.get('pending_rules', []))}",
             f"{'ROUTE':45} {'PASS':>5} {'SENSE':>5} {'BLOCK':>5}  STATE"]
    keys = sorted(set(routes) | inv)
    for k in keys[:60]:
        r = routes.get(k, {})
        st = "IMMUNE" if r.get("blocked") else ("SENSED " + ",".join(r.get("attacks", {})) if r.get("sensed") else ("alive" if k in inv or r.get("allowed") else "seen"))
        lines.append(f"{k[:45]:45} {r.get('allowed', 0):>5} {r.get('sensed', 0):>5} {r.get('blocked', 0):>5}  {st}")
    if len(keys) > 60:
        lines.append(f"... and {len(keys) - 60} more routes")
    return "\n".join(lines)


def cmd_status(args):
    env = _env()
    try:
        s = _get(GW + "/organism/state", env.get("GATEWAY_TOKEN")).json()
    except Exception as e:
        print(f"colony unreachable ({e}) — is it up? `python -m organisms up`")
        return 1
    print(render_status(s))
    if args.watch:
        try:
            while True:
                time.sleep(2)
                os.system("cls" if os.name == "nt" else "clear")
                print(render_status(_get(GW + "/organism/state", env.get("GATEWAY_TOKEN")).json()))
        except KeyboardInterrupt:
            pass
    return 0


def cmd_doctor(args):
    ok = True

    def check(name, fn):
        nonlocal ok
        try:
            msg = fn()
            print(f"  [ok] {name}: {msg}")
        except Exception as e:
            ok = False
            print(f"  [FAIL] {name}: {e}")

    print("Server Organisms doctor:")
    check("docker", lambda: subprocess.run(["docker", "info"], capture_output=True, check=True) and "daemon reachable")
    check(".env tokens", lambda: _need_tokens() or "all 4 credentials present")
    check("gateway", lambda: f"lease={_get(GW + '/health', timeout=5).json().get('lease_active')}")
    check("supervisor", lambda: f"epoch={_get(SUP + '/health', timeout=5).json().get('epoch')}")
    check("dashboard", lambda: f"HTTP {_get('http://127.0.0.1:18000/', timeout=5).status_code}")
    check("upstream", lambda: _check_upstream())
    return 0 if ok else 1


def _need_tokens():
    env = _env()
    missing = [k for k in ("BROKER_TOKEN", "GATEWAY_TOKEN", "AUDIT_TOKEN", "IDENTITY_HMAC_KEY") if not env.get(k)]
    if missing:
        raise RuntimeError(f"missing in .env (run `organisms init`): {', '.join(missing)}")
    return None


def _check_upstream():
    ups = _env().get("UPSTREAM_URL", "")
    if not ups:
        raise RuntimeError("UPSTREAM_URL not set — run `organisms init <repo> --upstream <url>`")
    host = ups.split("://", 1)[-1].split(":", 1)[0].split("/", 1)[0]
    if host not in ("127.0.0.1", "localhost", "host.docker.internal"):
        return f"{ups} configured (container-internal name — gateway verifies it at runtime)"
    try:
        code = _get(ups + "/health", timeout=5).status_code
    except Exception:
        try:
            code = _get(ups, timeout=5).status_code
        except Exception as e:
            raise RuntimeError(f"{ups} unreachable ({e}) — start YOUR app first")
    return f"{ups} reachable (HTTP {code})"


def cmd_kill(args):
    env = _env()
    r = _post(SUP + "/kill", env.get("BROKER_TOKEN"))
    print("lease withdrawn — colony halted." if r.status_code == 200 else f"failed: {r.text[:200]}")
    return 0 if r.status_code == 200 else 1


def cmd_revive(args):
    env = _env()
    r = _post(SUP + "/revive", env.get("BROKER_TOKEN"))
    print("colony revived." if r.status_code == 200 else f"failed: {r.text[:200]}")
    return 0 if r.status_code == 200 else 1


def cmd_down(args):
    return subprocess.run(["docker", "compose", "down"], cwd=ROOT).returncode


def cmd_logs(args):
    return subprocess.run(["docker", "compose", "logs", "--tail", "60", args.service or ""], cwd=ROOT).returncode


def build_parser():
    p = argparse.ArgumentParser(prog="organisms", description="Living immune layer for YOUR APIs.")
    sub = p.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("init", help="adopt a codebase: discover its APIs, configure the colony")
    i.add_argument("repo", help="path to YOUR app's repo")
    i.add_argument("--upstream", default="http://host.docker.internal:8000", help="where your app listens")
    i.add_argument("--replay-user", default="1", help="user id signed on replay traffic")
    i.add_argument("--network", default="", help="your app's Docker network name (for containerized apps)")
    i.set_defaults(fn=cmd_init)
    u = sub.add_parser("up", help="start the colony in front of your app")
    u.set_defaults(fn=cmd_up)
    s = sub.add_parser("status", help="watch every API: traffic, attacks, immunity")
    s.add_argument("--watch", action="store_true", help="refreshing terminal view")
    s.set_defaults(fn=cmd_status)
    d = sub.add_parser("doctor", help="diagnose setup problems")
    d.set_defaults(fn=cmd_doctor)
    k = sub.add_parser("kill", help="withdraw the lease (external kill switch)")
    k.set_defaults(fn=cmd_kill)
    v = sub.add_parser("revive", help="restore the lease")
    v.set_defaults(fn=cmd_revive)
    dn = sub.add_parser("down", help="stop the colony")
    dn.set_defaults(fn=cmd_down)
    lg = sub.add_parser("logs", help="tail service logs")
    lg.add_argument("service", nargs="?", default="")
    lg.set_defaults(fn=cmd_logs)
    return p


def main(argv=None):
    args = build_parser().parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
